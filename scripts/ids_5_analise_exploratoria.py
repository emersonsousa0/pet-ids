# 4. FUNÇÃO DE ANÁLISE EXPLORATÓRIA
# ------------------------------------------------------------

resultados_info = []
resultados_classes = []
resultados_nulos = []
resultados_dicionarios = []

def analisar_dataset(nome, df):

    print("\n" + "=" * 65)
    print(nome.upper())
    print("=" * 65)

    # Dimensão
    linhas, colunas = df.shape

    # Valores ausentes
    total_nulos = int(df.isnull().sum().sum())
    percentual_nulos = (total_nulos / df.size * 100) if df.size else 0

    # Duplicatas
    duplicatas = int(df.duplicated().sum())
    percentual_duplicatas = (
        duplicatas / linhas * 100 if linhas else 0
    )

    print(f"\nQuantidade de linhas: {linhas:,}")
    print(f"Quantidade de colunas: {colunas}")
    print(f"Total de células vazias: {total_nulos:,}")
    print(f"Percentual de células vazias: {percentual_nulos:.2f}%")
    print(f"Linhas duplicadas: {duplicatas:,}")
    print(f"Percentual de duplicatas: {percentual_duplicatas:.2f}%")

    resultados_info.append({
        "Dataset": nome,
        "Linhas": linhas,
        "Colunas": colunas,
        "Valores ausentes": total_nulos,
        "Percentual de células ausentes": round(percentual_nulos, 2),
        "Linhas duplicadas": duplicatas,
        "Percentual de duplicatas": round(percentual_duplicatas, 2)
    })

    # --------------------------------------------------------
    # DISTRIBUIÇÃO DAS CLASSES
    # --------------------------------------------------------

    coluna_label = next(
        (c for c in df.columns if c.lower() == "label"),
        None
    )

    if coluna_label:
        print("\nDISTRIBUIÇÃO DAS CLASSES:")

        contagem = df[coluna_label].value_counts(dropna=False)
        percentual = df[coluna_label].value_counts(
            normalize=True, dropna=False
        ) * 100

        tabela_classes = pd.DataFrame({
            "Quantidade": contagem,
            "Percentual": percentual.round(2)
        })

        display(tabela_classes)

        for classe, quantidade in contagem.items():
            resultados_classes.append({
                "Dataset": nome,
                "Classe": classe,
                "Quantidade": int(quantidade),
                "Percentual": round(float(percentual[classe]), 2)
            })
    else:
        print("\nA coluna Label não foi encontrada.")

    # --------------------------------------------------------
    # VALORES AUSENTES POR COLUNA
    # --------------------------------------------------------

    print("\nVALORES AUSENTES POR COLUNA:")

    tabela_nulos = pd.DataFrame({
        "Coluna": df.columns,
        "Valores ausentes": df.isnull().sum().values,
        "Percentual (%)": (
            df.isnull().mean().values * 100
        ).round(2)
    })

    tabela_nulos = tabela_nulos.sort_values(
        "Valores ausentes", ascending=False
    )

    display(tabela_nulos)

    for _, linha in tabela_nulos.iterrows():
        resultados_nulos.append({
            "Dataset": nome,
            "Coluna": linha["Coluna"],
            "Valores ausentes": int(linha["Valores ausentes"]),
            "Percentual (%)": linha["Percentual (%)"]
        })

    # --------------------------------------------------------
    # DICIONÁRIO DE TODAS AS COLUNAS
    # --------------------------------------------------------

    print("\nDICIONÁRIO DE DADOS:")

    dicionario = []

    for coluna in df.columns:

        descricao = descricoes.get(
            coluna,
            "Atributo presente no dataset. "
            "Significado específico não documentado nas fontes consultadas."
        )

        exemplos = df[coluna].dropna().astype(str).unique()[:3]

        dicionario.append({
            "Dataset": nome,
            "Coluna": coluna,
            "Tipo de dado": str(df[coluna].dtype),
            "Descrição": descricao,
            "Valores únicos": int(df[coluna].nunique(dropna=True)),
            "Valores ausentes": int(df[coluna].isnull().sum()),
            "Exemplos": ", ".join(exemplos)
        })

    tabela_dicionario = pd.DataFrame(dicionario)
    display(tabela_dicionario)

    resultados_dicionarios.extend(dicionario)

    # --------------------------------------------------------
    # VISUALIZAÇÃO GERAL
    # --------------------------------------------------------

    print("\nPRIMEIRAS CINCO LINHAS:")
    display(df.head())

# ------------------------------------------------------------
